"""Writes src/palettes.css from the palette below.
All text on the site is CREAM, so each palette's colours are given roles by what they can carry:
  bg, surface: running text (4.5:1 against cream)
  field (the photos band) and button: large or bold text only (3:1, buttons are set at 19px bold)
  deco: no text at all (film perforations, the active project's underline, the marked phrase)
Run after changing a colour: python3 scripts/build-palettes.py"""

CREAM = '#fff2e0'
PALETTES = [
    # id, label, bg, surface (None: a step lighter than bg), field, button, deco
    ('rose', 'Rose', '#342726', None, '#6b8f71', '#6b8f71', '#e56399'),
]


def rgb(h): return [int(h.lstrip('#')[i:i + 2], 16) for i in (0, 2, 4)]
def hexc(c): return '#' + ''.join(f'{round(max(0, min(255, x))):02x}' for x in c)
def mix(a, b, t): return hexc([x + (y - x) * t for x, y in zip(rgb(a), rgb(b))])


def lum(h):
    c = [x / 255 for x in rgb(h)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def cr(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True)
    return (la + 0.05) / (lb + 0.05)


NEEDS = {'bg': 4.5, 'surface': 4.5, 'field': 3, 'button': 3}
out = ['/* Generated by scripts/build-palettes.py. Every text colour is the cream; the palette sets the grounds and accents. */']
failed = False
for n, (pid, label, bg, surface, field, button, deco) in enumerate(PALETTES):
    surface = surface or mix(bg, CREAM, 0.07)
    roles = dict(bg=bg, surface=surface, field=field, button=button)
    checks = {k: cr(CREAM, c) for k, c in roles.items()}
    bad = [k for k, c in checks.items() if c < NEEDS[k]]
    failed |= bool(bad)
    print(label.ljust(6), '  '.join(f'cream/{k} {c:.2f}' for k, c in checks.items()), '  FAIL: ' + ', '.join(bad) if bad else '  ok')
    v = {'bg': bg, 'surface': surface, 'field': field, 'ink': CREAM, 'muted': CREAM,
         'accent': button, 'accent-strong': mix(button, bg, 0.25), 'accent-ink': CREAM,
         'deco': deco, 'line': mix(bg, CREAM, 0.16), 'placeholder': CREAM}
    sel = ':root'
    out.append(sel + ' {\n' + '\n'.join(f'  --{k}: {c};' for k, c in v.items()) + '\n}')

open('src/palettes.css', 'w').write('\n\n'.join(out) + '\n')
raise SystemExit(1 if failed else 0)
